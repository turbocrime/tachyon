/// Volatile-wipe a Pallas scalar (`Fq`) in place.
#[inline(always)]
pub(crate) fn wipe_fq(value: &mut Fq) {
    // Safety: pasta_curves::Fq is a plain field element with no heap
    // allocations, internal pointers, or Drop implementation.
    unsafe {
        let bytes: *mut u8 = ptr::from_mut(value).cast();
        slice::from_raw_parts_mut(bytes, size_of::<Fq>()).zeroize();
    }
}

