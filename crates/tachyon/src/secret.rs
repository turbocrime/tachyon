//! Secret newtypes and in-place zeroization helpers for material whose
//! underlying types do not implement [`zeroize::Zeroize`].
//!
//! Each `Secret*` newtype owns the zeroize-on-drop behaviour for exactly one
//! concrete field/point type, so secret types elsewhere can wrap one and
//! `#[derive(Zeroize, ZeroizeOnDrop)]` instead of hand-writing the impls.
//! The free `wipe_*` helpers perform the volatile byte-wipe and are reused for
//! transient reddsa values that are not stored behind a `Secret*` newtype.

// TODO: this is kind of a mess. there are still lots of transient copies
// generated by computing operations on as_ref outputs. a real solution would
// require zeroize support in upstream pasta_curves.

#![allow(unsafe_code, clippy::inline_always, reason = "zeroization helpers")]
#![allow(dead_code, reason = "todo")]

use core::{mem::size_of, ptr, slice};

use derive_more::{Add, AddAssign, AsRef, Debug, Eq as TotalEq, From, Neg, PartialEq};
use pasta_curves::{EpAffine, Fp, Fq};
use zeroize::{Zeroize, ZeroizeOnDrop};

use crate::reddsa;

/// A secret Pallas base field element (`Fp`) that zeroizes itself on drop.
#[derive(Add, AddAssign, AsRef, Clone, Debug, From, Neg, PartialEq, TotalEq)]
pub(crate) struct SecretFp(#[debug(skip)] Fp);

impl Zeroize for SecretFp {
    fn zeroize(&mut self) {
        wipe_fp(&mut self.0);
    }
}

impl Drop for SecretFp {
    fn drop(&mut self) {
        self.zeroize();
    }
}

impl ZeroizeOnDrop for SecretFp {}

